let currentLang = localStorage.getItem('healthpulse_lang') || 'en';

function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}

function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) langCode = 'en';
  currentLang = langCode;
  localStorage.setItem('healthpulse_lang', langCode);

  // Update all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // Update placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  // Update active state in language dropdown
  document.querySelectorAll('.lang-select-option').forEach(opt => {
    opt.classList.toggle('font-bold', opt.getAttribute('data-lang') === langCode);
    opt.classList.toggle('text-indigo-600', opt.getAttribute('data-lang') === langCode);
  });

  const langBadge = document.getElementById('currentLangLabel');
  if (langBadge) {
    const names = {
      en: 'English', hi: 'हिन्दी', bn: 'বাংলা', te: 'తెలుగు', ta: 'தமிழ்',
      mr: 'मराठी', gu: 'ગુજરાતી', kn: 'ಕನ್ನಡ', ml: 'മലയാളം', pa: 'ਪੰਜਾਬੀ', or: 'ଓଡ଼ିଆ'
    };
    langBadge.textContent = names[langCode] || 'English';
  }
}
